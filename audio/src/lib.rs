//! irealwx_audio — звуковой слой (метроном/клик), аналог `sound.py` в irealstudio.
//!
//! Границы крейта:
//! - Отвечает ТОЛЬКО за синтез и вывод аудио в реальном времени.
//! - Ничего не знает о тактах/гармонии: принимает простые события
//!   (тик метронома с акцентом, длина такта), а не модели песен.
//! - Рядом с ним живут `irealwx_midi` (тот же тактовый тайминг) и
//!   `irealwx_speech` (речь) — три независимых «уха» одного ритма.
//!
//! Платформа: реальная реализация — cpal под Windows (как договорились:
//! звук через cpal, миди через midir). Здесь держим чистый контракт,
//! чтобы слой можно было чинить и заменять отдельно от остального.

/// Контракт аудио-бэкенда: умеет играть клик метронома.
pub trait Metronome {
    /// Воспроизвести один клик.
    /// `accented` — первая доля такта (выделяется громкостью/тоном).
    fn click(&self, accented: bool);
}

/// Заглушка без устройства — для сборки/тестов на не-Windows хостах.
pub struct NullMetronome;

impl Metronome for NullMetronome {
    fn click(&self, _accented: bool) {}
}
