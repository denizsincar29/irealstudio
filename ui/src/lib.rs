//! irealwx_ui — GUI-слой на wxDragon (Windows-only, собирается на Windows).
//!
//! Сценарий доступности (решение с Денизом, #irealstudio):
//! - Главное окно НЕ имеет a11y-контролов, как в воркспейс-программах:
//!   весь ввод через **альт-меню** (нативный HMENU-менюбар) и хоткеи.
//! - Панель тактов (аккордовая сетка) рисуется в `on_paint` на кастомном
//!   канвасе: она ТОЛЬКО видна, в дерево доступности не попадает.
//! - При навигации стрелками по тактам содержимое ОЗВУЧИВАЕТСЯ через
//!   `irealwx_speech` (не через a11y-события).
//! - Обычные wx-контролы нужны только в форме создания/редактирования
//!   цифровки (диалог).
//!
//! Внутренние модули (каждый чинится отдельно):
//!   app      — сборка окна, связка меню/панели/статуса
//!   menu     — пункты альт-меню (как app_menu.py в irealstudio)
//!   grid     — панель тактов: on_paint + навигация стрелками (озвучка наружу)
//!   dialogs  — форма цифровки и остальные wx-диалоги (как dialogs.py)
//!   keys     — хоткеи (как app_keys.py)
//!   playback — драйвер проигрывания: тактовый таймер → audio/midi/speech

/// Тип события «пользователь прошёлся по тактам» — то, что озвучивается.
pub struct MeasureNavEvent {
    pub index: usize,
    pub announcement: String, // готовый текст для speech (числа прописью и т.п.)
}
